-- Snowflake setup for Claude's look-only login (GEN-980 lever e / GEN-953 step 4).
-- Run in Snowsight as ACCOUNTADMIN, in this order. Step 0 only looks.
-- <PUBLIC_KEY> comes from %TEMP%\snowflake-reader-public-key.txt (line 1), written by
-- snowflake-reader-setup.ps1. It is the PUBLIC key; it is not secret.

-- Step 0: look first (no changes)
USE ROLE ACCOUNTADMIN;
SHOW FUTURE GRANTS IN DATABASE DATALAKE;
SHOW FUTURE GRANTS IN DATABASE MEMORY_PIRATES;
SHOW SCHEMAS IN DATABASE DATALAKE;
SHOW SCHEMAS IN DATABASE MEMORY_PIRATES;
SHOW GRANTS TO ROLE PUBLIC;          -- does SNOWFLAKE.CORTEX_USER reach every role?
SHOW ROLES LIKE 'CLAUDE%';
SHOW USERS LIKE 'CLAUDE%';
SHOW WAREHOUSES LIKE 'CLAUDE%';

-- Step 1: role, compute and spending cap
CREATE ROLE IF NOT EXISTS CLAUDE_READ COMMENT = 'Claude look-only role (GEN-980). SELECT and viewer roles only.';
CREATE WAREHOUSE IF NOT EXISTS CLAUDE_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  COMMENT = 'Compute for Claude look-only queries (GEN-980)';
CREATE RESOURCE MONITOR IF NOT EXISTS CLAUDE_MONITOR WITH
  CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE CLAUDE_WH SET RESOURCE_MONITOR = CLAUDE_MONITOR;
GRANT USAGE ON WAREHOUSE CLAUDE_WH TO ROLE CLAUDE_READ;

-- Step 2: what the role may read (repeat per database; add schema-level FUTURE grants for any
-- schema that Step 0 showed already has its own future grants)
GRANT USAGE ON DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT USAGE ON ALL SCHEMAS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL TABLES IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL VIEWS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL MATERIALIZED VIEWS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL DYNAMIC TABLES IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE TABLES IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE VIEWS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE MATERIALIZED VIEWS IN DATABASE DATALAKE TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE DATALAKE TO ROLE CLAUDE_READ;

GRANT USAGE ON DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT USAGE ON ALL SCHEMAS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL TABLES IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL VIEWS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL MATERIALIZED VIEWS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON ALL DYNAMIC TABLES IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE TABLES IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE VIEWS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE MATERIALIZED VIEWS IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE MEMORY_PIRATES TO ROLE CLAUDE_READ;

GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE CLAUDE_READ;       -- TASK_HISTORY
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE CLAUDE_READ;  -- QUERY_HISTORY
GRANT DATABASE ROLE SNOWFLAKE.OBJECT_VIEWER TO ROLE CLAUDE_READ;      -- object definitions
-- Never: USAGE on any procedure or function, OWNERSHIP, CREATE, MODIFY, or another role.

-- Step 3: the login
CREATE USER IF NOT EXISTS CLAUDE_READER
  TYPE = SERVICE DEFAULT_ROLE = CLAUDE_READ DEFAULT_WAREHOUSE = CLAUDE_WH
  COMMENT = 'Claude look-only login (GEN-980). Key on Erez PC Credential Manager.';
GRANT ROLE CLAUDE_READ TO USER CLAUDE_READER;
ALTER USER CLAUDE_READER ADD KEY PAIR CLAUDE_PC_1
  PUBLIC_KEY = '<PUBLIC_KEY>' ROLE_RESTRICTION = 'CLAUDE_READ'
  COMMENT = 'Erez PC, Windows Credential Manager claude-snowflake-reader';
-- Stop the look-only login copying data out (COPY INTO an outside URL or a Snowflake stage);
-- found by the Pass B code review, applied 2026-10-29. Only ACCOUNTADMIN can undo it.
ALTER USER CLAUDE_READER SET PREVENT_UNLOAD_TO_INLINE_URL = TRUE PREVENT_UNLOAD_TO_INTERNAL_STAGES = TRUE;
-- Applied as run: role grants also gave schema-level FUTURE TABLES/VIEWS grants on all 8
-- schemas (DATALAKE: BIGQUERY, MRR, PUBLIC, SANDBOX; MEMORY_PIRATES: BACKUP, GAME, LEXICON,
-- PUBLIC). Every role also inherits Snowflake's PUBLIC role: USAGE/OPERATE on warehouse
-- RESEARCHING, SNOWFLAKE.CORTEX_USER (AI functions), and SNOWFLAKE_LEARNING_ROLE (CREATE SCHEMA
-- in SNOWFLAKE_LEARNING_DB). Those are account defaults, left for Erez to decide.
-- Fallback if ADD KEY PAIR is refused or sign-in then fails on the role check:
-- ALTER USER CLAUDE_READER SET RSA_PUBLIC_KEY = '<PUBLIC_KEY>';

-- Step 4: confirm
SHOW GRANTS TO ROLE CLAUDE_READ;
SHOW GRANTS TO USER CLAUDE_READER;
DESC USER CLAUDE_READER;
SHOW WAREHOUSES LIKE 'CLAUDE_WH';
SHOW RESOURCE MONITORS LIKE 'CLAUDE_MONITOR';

-- Undo (only if Erez asks): DROP USER CLAUDE_READER; DROP WAREHOUSE CLAUDE_WH;
